def _get(target: str):
    """Resolve `pkg.module.Class.member` against the live package."""
    obj = importlib.import_module(target)
    return obj


class ApiSurfaceCase(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cwd = os.getcwd()
        os.chdir(ROOT)
        try:
            cls.current = stores_api.surface()
        finally:
            os.chdir(cwd)
        cls.baseline = cls._load(BASELINE)
        cls.pre_b1 = cls._load(BASELINE_PRE_B1)

    @staticmethod
    def _load(path):
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)


class TestSurfaceIsFrozen(ApiSurfaceCase):
    def test_the_baseline_is_not_empty(self):
        self.assertGreaterEqual(len(self.baseline), 16)
        self.assertIn("stores.history_repo", self.baseline)

    def test_b1_only_widened_the_surface_it_promised(self):
        """Against the surface as AREA B found it (`api_baseline_pre_b1`).

        This is the real "no other area had to change" proof: every store
        keeps its name, every parameter it used to accept is still accepted,
        and the only differences are the `WIDENED` ones B1 set out to make.
        """
        self.assertEqual(
            stores_api.diff(self.pre_b1, self.current, WIDENED,
                            allow_new_modules=True), [],
            "the pre-B1 surface moved in a way the design doc does not "
            "account for")

    def test_nothing_was_removed_or_re_signedatured(self):
        problems = stores_api.diff(self.baseline, self.current, WIDENED,
                                   allow_new_modules=True)
        self.assertEqual(problems, [], "\n".join(problems))

    def test_the_three_frozen_modules_did_not_move_at_all(self):
        frozen_baseline = {k: v for k, v in self.baseline.items()
                           if k in FROZEN}
        frozen_current = {k: v for k, v in self.current.items()
                          if k in FROZEN}
        self.assertEqual(
            stores_api.diff(frozen_baseline, frozen_current,
                            allow_new_modules=True), [],
            "stores/history_models.py, jsonio.py and migration.py are frozen "
            "for every area (plan §7.3 rule 2)")

    def test_every_allowlisted_name_keeps_its_old_parameters(self):
        for dotted in sorted(WIDENED):
            parts = dotted.split(".")
            self.assertEqual(parts[0], "stores", f"{dotted} is not in stores/")
            module = f"stores.{parts[1]}"
            rest = ".".join(parts[2:])
            expected = self._lookup(self.baseline, module, rest)
            got = self._lookup(self.current, module, rest)
            with self.subTest(name=dotted):
                self.assertIsNotNone(expected, f"{dotted} is not in the "
                                                "baseline — drop it from "
                                                "WIDENED")
                self.assertIsNotNone(got, f"{dotted} was REMOVED")
                if "params" in expected:
                    self.assertTrue(set(expected["params"])
                                    <= set(got.get("params") or ()),
                                    f"{dotted} dropped or renamed a parameter: "
                                    f"{expected['params']} -> "
                                    f"{got.get('params')}")

    @staticmethod
    def _lookup(tree, module, rest):
        entry = tree.get(module)
        if entry is None:
            return None
        if "." not in rest:
            if rest in entry["functions"]:
                return entry["functions"][rest]
            if rest in entry["constants"]:
                return {"kind": "constant"}
            if rest in entry["classes"]:
                return {"kind": "class"}
            return None
        klass, method = rest.split(".", 1)
        return entry["classes"].get(klass, {}).get(method)


class TestOtherAreasKeepImporting(ApiSurfaceCase):
    def test_every_imported_name_still_exists(self):
        for module, names in REQUIRED.items():
            mod = _get(module)
            for name in names:
                with self.subTest(name=f"{module}.{name}"):
                    target = mod
                    for part in name.split("."):
                        target = getattr(target, part)
                        self.assertIsNotNone(target)

    def test_stores_imports_outside_the_package_are_untouched(self):
        # plan §6.2 exit criterion 3: no other area had to edit an import
        count = 0
        for pkg in ("services", "backend", "actions", "bridge", "app"):
            for base, dirs, files in os.walk(os.path.join(ROOT, pkg)):
                dirs[:] = [d for d in dirs if d != "__pycache__"]
                for name in files:
                    if not name.endswith(".py"):
                        continue
                    with open(os.path.join(base, name), encoding="utf-8") as fh:
                        count += sum(1 for line in fh
                                     if line.lstrip().startswith("from stores")
                                     or " from stores." in line
                                     or "from stores import" in line)
        # The count was 33 on the pre-refactor base AREA B was authored
        # against. A's run-engine fix (+1, stores.user_memory now imported at
        # runtime in services/run/progress.py) and D's chat_sync extraction
        # (+3: SyncResult/MAX_LIVE_ITEMS/align_batch/MessageRecord) added
        # legitimate imports *before* B was merged; the B merge itself adds
        # zero. The undo-restore fix (2026-09-11) adds +2: the new leaf
        # module stores/world_lock.py is imported by services/undo_archive.py
        # (the archive command retries a locked world) and by
        # services/history/mutate.py (the timeline save does the same). The
        # invariant this pins is "the stores refactor must not force another
        # area to edit an import" — bump this number only when another area
        # legitimately grows the surface.
        self.assertEqual(count, 39,
                         "stores/ must be refactored without touching a single "
                         "import in another area (integrated baseline: 37)")


