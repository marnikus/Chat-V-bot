"""AREA B — the public surface of `stores/` is frozen; only additions allowed.

Design ref: docs/archive/2026-09-09-four-area-refactor/REFACTOR_2026-09-09_AREA_B_DESIGN.md §3 and §6.1;
plan §7.3 rule 1 ("No area renames, moves, or changes the signature of any
symbol that another area imports").

`api_baseline.json` (generated by `tools/metrics/stores_api.py --write`) records
every public module-level symbol of `stores/`, every public method of every
class, and their `inspect.signature` text plus parameter names. This test
rebuilds that surface from the live package and fails on

  * a removed symbol,
  * a removed method,
  * a signature change that is not on the documented allowlist,
  * an allowlisted signature that renamed or dropped a parameter (a widening
    must keep every old parameter, otherwise the callers B1 promises not to
    touch would break),
  * any change at all inside the three frozen modules.

Run with:  python3 tests/unit/stores/test_stores_public_api.py
      or:  python tools/metrics/stores_api.py --write   (after a deliberate change)
"""

import importlib
import importlib.util
import json
import os
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__)))))
sys.path.insert(0, ROOT)

HERE = os.path.dirname(os.path.abspath(__file__))
BASELINE = os.path.join(HERE, "api_baseline.json")

_spec = importlib.util.spec_from_file_location(
    "stores_api", os.path.join(ROOT, "tools", "metrics", "stores_api.py"))
stores_api = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(stores_api)

#: the names B1 widens ON PURPOSE (docs/archive/2026-09-09-four-area-refactor/REFACTOR_2026-09-09_AREA_B_DESIGN.md
#: §6.1). Every entry must keep all of its old parameters — a widening, never
#: a rename. Anything not on this list that differs fails the test.
WIDENED = frozenset({
    # ── P1-3: one constructor for every config store ─────────────────
    # `Store(atomic | path, *, data=None)`; the payload slot of the old
    # signature keeps its name (`path`, `data`, `save_now`, `config`), so
    # every call form that worked before still works.
    "stores.atomic.AtomicJsonStore.__init__",       # path | another atomic
    "stores.session_store.SessionStore.__init__",
    "stores.session_store.SessionStore.set",        # `save` joins `save_now`
    "stores.settings_store.SettingsStore.__init__",
    "stores.settings_store.SettingsStore.set",       # `save` joins `save_now`
    "stores.labels_file_store.LabelsFileStore.__init__",
    "stores.undo_store.UndoStore.__init__",
    "stores.block_store.BlockStore.__init__",
    "stores.bookmark_store.BookmarkStore.__init__",
    "stores.preset_store.PresetStore.__init__",      # config | atomic | path
    # ── one lifecycle: `save(force=False)` / `flush()` answer `bool`, and
    #    every store can be told to persist (ConfigManager.save() names all
    #    seven, and two of them used to have no `save()` at all) ──────────
    "stores.undo_store.UndoStore.save",
    "stores.undo_store.UndoStore.flush",
    "stores.block_store.BlockStore.save",
    "stores.block_store.BlockStore.flush",
    "stores.bookmark_store.BookmarkStore.save",
    "stores.bookmark_store.BookmarkStore.flush",
    "stores.labels_file_store.LabelsFileStore.data",
    # ── annotations loosened to "accept what the caller has": a path object,
    #    an AtomicJsonStore, any mapping. Parameters are unchanged. ───────
    "stores.labels_file_store.LabelsFileStore.set_data",
    "stores.block_store.BlockStore.set_all",
    "stores.block_store.BlockStore.save_custom_block",
    "stores.bookmark_store.BookmarkStore.set_all",
    # ── stores/add/removes report whether anything changed (both
    #    `test_stores_split.py` and `bridge/cdp_bridge.py` read that
    #    truthiness; the value is still a Result) ─────────────────────
    "stores.bookmark_store.BookmarkStore.add",
    "stores.bookmark_store.BookmarkStore.remove",
})

#: `tests/unit/stores/api_baseline_pre_b1.json` is the surface as AREA B
